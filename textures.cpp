// ═══════════════════════════════════════════════════════════════
//  PER-FRAME LIGHTING AND PALETTE BUILDERS
// ═══════════════════════════════════════════════════════════════
static const float FACE_K[TF_COUNT] = { 0.85f, 0.30f, 0.55f, 0.70f, 0.0f };   // as colors.cpp
static int32_t sMul[TF_COUNT][3];      // 8.8 per channel: ambient + light * k
static int32_t sUp[3];                 // warm uplight (8.8) at full amount
static uint8_t sDayWin[TEX_WIN_STATES][3][3];   // punched windows by day (RGB888)
static uint8_t sCurWin[TEX_WIN_STATES][3][3];   // curtain wall gradient by day
static int     sNight32 = 0;

static inline uint16_t pack888(int r, int g, int b) {
  return rgb((uint8_t)iclamp(r, 0, 255), (uint8_t)iclamp(g, 0, 255), (uint8_t)iclamp(b, 0, 255));
}
static inline void unpack565(uint16_t c, int& r, int& g, int& b) {
  r = ((c >> 11) & 31) * 255 / 31;
  g = ((c >> 5) & 63) * 255 / 63;
  b = (c & 31) * 255 / 31;
}
static inline void mix3(uint8_t out[3], const int a[3], const int b[3], float t) {
  for (int i = 0; i < 3; i++) out[i] = (uint8_t)iclamp((int)(a[i] + (b[i] - a[i]) * t + 0.5f), 0, 255);
}

void tex_beginFrame() {
  const float light[3] = { pal.lightR, pal.lightG, pal.lightB };
  const float amb[3] = { pal.ambR, pal.ambG, pal.ambB };
  for (int f = 0; f < TF_TUNNEL; f++)
    for (int c = 0; c < 3; c++) sMul[f][c] = (int32_t)((amb[c] + light[c] * FACE_K[f]) * 256.0f);
  {   // tunnel lining: lamp light, independent of the sun
    int tr, tg, tb;
    unpack565(pal.tunnelLight, tr, tg, tb);
    sMul[TF_TUNNEL][0] = 60 + tr * 150 / 255;
    sMul[TF_TUNNEL][1] = 60 + tg * 150 / 255;
    sMul[TF_TUNNEL][2] = 60 + tb * 150 / 255;
  }
  int lr, lg, lb;
  unpack565(pal.lampLight, lr, lg, lb);
  sUp[0] = lr; sUp[1] = lg; sUp[2] = lb;   // x amount / 255 later
  sNight32 = (int)(pal.night * 32.0f + 0.5f);

  // Day window looks from the current sky (they darken with it)
  int wd[3], sm[3], sh[3], st[3];
  unpack565(pal.windowDay, wd[0], wd[1], wd[2]);
  unpack565(pal.skyMid, sm[0], sm[1], sm[2]);
  unpack565(pal.skyHorizon, sh[0], sh[1], sh[2]);
  unpack565(pal.skyTop, st[0], st[1], st[2]);
  int dk[3] = { wd[0] * 45 / 100, wd[1] * 48 / 100, wd[2] * 55 / 100 };
  int blind[3] = { 200 * (wd[0] + 60) / 255, 190 * (wd[1] + 60) / 255, 168 * (wd[2] + 60) / 255 };
  int curt[3] = { 190 * (wd[0] + 40) / 255, 150 * (wd[1] + 40) / 255, 130 * (wd[2] + 40) / 255 };
  int white[3] = { 255, 255, 255 };
  for (int s = 0; s < TEX_WIN_STATES; s++) {
    uint8_t (*w)[3] = sDayWin[s];
    switch (s) {
      case 0: mix3(w[0], wd, sm, 0.30f); mix3(w[1], wd, sh, 0.55f); mix3(w[2], wd, dk, 0.5f); break;
      case 1: mix3(w[0], wd, dk, 0.70f); mix3(w[1], wd, dk, 0.40f); mix3(w[2], dk, dk, 0); break;
      case 2: mix3(w[0], wd, blind, 0.65f); mix3(w[1], blind, white, 0.2f); mix3(w[2], wd, dk, 0.4f); break;
      case 3: mix3(w[0], wd, sh, 0.60f); mix3(w[1], sh, white, 0.45f); mix3(w[2], wd, sm, 0.3f); break;
      case 4: mix3(w[0], wd, st, 0.35f); mix3(w[1], wd, sm, 0.6f); mix3(w[2], wd, dk, 0.6f); break;
      case 5: mix3(w[0], wd, curt, 0.55f); mix3(w[1], wd, sh, 0.4f); mix3(w[2], curt, dk, 0.4f); break;
      case 6: mix3(w[0], wd, dk, 0.50f); mix3(w[1], wd, sh, 0.3f); mix3(w[2], dk, dk, 0); break;
      default: mix3(w[0], wd, sm, 0.15f); mix3(w[1], wd, white, 0.25f); mix3(w[2], wd, dk, 0.3f); break;
    }
    // curtain wall: street reflection at the bottom -> sky at the top
    float t = s / (float)(TEX_WIN_STATES - 1);
    int lo[3] = { (dk[0] + wd[0]) / 2, (dk[1] + wd[1]) / 2, (dk[2] + wd[2]) / 2 };
    int hi[3];
    for (int i = 0; i < 3; i++) hi[i] = (sh[i] * 2 + sm[i]) / 3;
    uint8_t mid[3];
    mix3(mid, lo, hi, t);
    int m[3] = { mid[0], mid[1], mid[2] };
    mix3(sCurWin[s][0], m, m, 0);
    mix3(sCurWin[s][1], m, white, 0.22f);
    mix3(sCurWin[s][2], m, dk, 0.45f);
  }
}

static inline uint16_t shadeSlot(const uint8_t c[3], const int32_t* mul) {
  return pack888((c[0] * mul[0]) >> 8, (c[1] * mul[1]) >> 8, (c[2] * mul[2]) >> 8);
}

void tex_buildPalette(uint16_t out[TS_COUNT], const TexColors& c, int face, uint16_t fogc, int fog32) {
  const int32_t* mul = sMul[iclamp(face, 0, TF_COUNT - 1)];
  for (int s = 0; s < TS_COUNT; s++) out[s] = shadeSlot(c.rgb[s], mul);
  // emissive slots: towards the glow colour with the night
  for (int e = 0; e < 2; e++) {
    uint16_t g = rgb(c.glow[e][0], c.glow[e][1], c.glow[e][2]);
    out[TS_EMITA + e] = blend565(g, out[TS_EMITA + e], (uint32_t)sNight32);
  }
  // unpatched window slots: the first day look
  for (int k = 0; k < 3; k++) out[TS_WINA + k] = shadeSlot(sDayWin[0][k], mul);
  if (fog32 > 0)
    for (int s = 0; s < TS_COUNT; s++) out[s] = blend565(fogc, out[s], (uint32_t)fog32);
}

void tex_buildUplitPalette(uint16_t out[TS_COUNT], const TexColors& c, int face, uint16_t fogc,
                           int fog32, float amount) {
  const int32_t* mul = sMul[iclamp(face, 0, TF_COUNT - 1)];
  int32_t m[3];
  for (int i = 0; i < 3; i++) m[i] = mul[i] + (int32_t)(sUp[i] * amount);
  for (int s = 0; s < TS_COUNT; s++) out[s] = shadeSlot(c.rgb[s], m);
  for (int e = 0; e < 2; e++) {
    uint16_t g = rgb(c.glow[e][0], c.glow[e][1], c.glow[e][2]);
    out[TS_EMITA + e] = blend565(g, out[TS_EMITA + e], (uint32_t)sNight32);
  }
  for (int k = 0; k < 3; k++) out[TS_WINA + k] = shadeSlot(sDayWin[0][k], m);
  if (fog32 > 0)
    for (int s = 0; s < TS_COUNT; s++) out[s] = blend565(fogc, out[s], (uint32_t)fog32);
}

// Night window colours: warm, white, cool, TV blue (main, upper, blind)
static const uint8_t LIT[4][3][3] = {
  { { 255, 196, 110 }, { 255, 222, 150 }, { 200, 140, 80 } },
  { { 255, 236, 190 }, { 255, 248, 222 }, { 214, 192, 150 } },
  { { 200, 226, 255 }, { 232, 242, 255 }, { 150, 180, 220 } },
  { { 110, 150, 255 }, { 150, 180, 255 }, { 70, 90, 180 } },
};

void tex_windowSets(uint16_t out[TEX_WIN_STATES][3], int face, const uint8_t tint[3], bool curtain,
                    uint16_t fogc, int fog32) {
  // day looks (tinted, mildly shaded per face) for states 0..7; the
  // renderer swaps in a lit colour (tex_litSet) where a window is lit
  const int fk = face == TF_SHADE ? 205 : (face == TF_LIT ? 256 : 232);
  const int tr = (tint[0] + 128) * fk >> 8, tg = (tint[1] + 128) * fk >> 8, tb = (tint[2] + 128) * fk >> 8;
  for (int s = 0; s < TEX_WIN_STATES; s++)
    for (int k = 0; k < 3; k++) {
      const uint8_t* w = curtain ? sCurWin[s][k] : sDayWin[s][k];
      uint16_t c = pack888(w[0] * tr / 255, w[1] * tg / 255, w[2] * tb / 255);
      out[s][k] = fog32 > 0 ? blend565(fogc, c, (uint32_t)fog32) : c;
    }
}

void tex_litSets(uint16_t out[4][3], uint16_t fogc, int fog32) {
  for (int s = 0; s < 4; s++)
    for (int k = 0; k < 3; k++) {
      uint16_t c = rgb(LIT[s][k][0], LIT[s][k][1], LIT[s][k][2]);
      out[s][k] = fog32 > 0 ? blend565(fogc, c, (uint32_t)fog32) : c;
    }
}

static inline uint16_t mulBase(int r, int g, int b, const uint16_t* f) {
  return pack888((r * f[0]) >> 7, (g * f[1]) >> 7, (b * f[2]) >> 7);
}

void tex_rowPalette(uint16_t out[TS_COUNT], int id, uint16_t base, uint16_t fogc, int fog32) {
  const RowFactors& F = ROWF[iclamp(id, 0, RT_COUNT - 1)];
  int r, g, b;
  unpack565(base, r, g, b);
  for (int s = 0; s < TS_COUNT; s++) {
    uint16_t c = mulBase(r, g, b, F.f[s]);
    out[s] = fog32 > 0 ? blend565(fogc, c, (uint32_t)fog32) : c;
  }
}

void tex_asphaltPalette(uint16_t out[TS_COUNT], uint16_t base, uint32_t show, uint16_t fogc, int fog32) {
  const RowFactors& F = ROWF[RT_ASPHALT];
  int r, g, b;
  unpack565(base, r, g, b);
  for (int s = 0; s < TS_COUNT; s++) {
    const uint16_t* f = (show & (1u << s)) ? F.f[s] : F.f[TS_BASE];
    uint16_t c = mulBase(r, g, b, f);
    out[s] = fog32 > 0 ? blend565(fogc, c, (uint32_t)fog32) : c;
  }
}

void tex_pavementPalette(uint16_t out[TS_COUNT], uint16_t slab, uint16_t kerb, uint16_t fogc, int fog32) {
  const RowFactors& F = ROWF[RT_PAVEMENT];
  int r, g, b, kr, kg, kb;
  unpack565(slab, r, g, b);
  unpack565(kerb, kr, kg, kb);
  for (int s = 0; s < TS_COUNT; s++) {
    uint16_t c = (s == TS_TRIM || s == TS_TRIMD) ? mulBase(kr, kg, kb, F.f[s]) : mulBase(r, g, b, F.f[s]);
    out[s] = fog32 > 0 ? blend565(fogc, c, (uint32_t)fog32) : c;
  }
}
