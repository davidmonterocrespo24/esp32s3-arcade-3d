/*
  ═══════════════════════════════════════════════════════════════
  PROCEDURAL TEXTURES — implementation

  Each texture is an analytic design: evalWall() / evalRow() return the
  semantic slot of the texel at level-0 coordinates (u, v). Every mip
  level is generated by point-sampling the same design at its own texel
  centres (thin details drop out, windows survive as dots); noise is
  tileable value noise from hash32 with fewer octaves on coarse levels.
  Generation runs once at boot (~23 K texels).
  ═══════════════════════════════════════════════════════════════
*/

