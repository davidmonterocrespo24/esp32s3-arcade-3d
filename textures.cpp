// ═══════════════════════════════════════════════════════════════
//  NOISE (tileable value noise from hash32)
// ═══════════════════════════════════════════════════════════════
static inline float hrand(int x, int y, uint32_t seed) {
  return (float)(hash32((uint32_t)x * 0x8DA6B343u ^ (uint32_t)y * 0xD8163841u ^ seed) >> 8) *
         (1.0f / 16777216.0f);
}

static inline int wrapI(int a, int p) { a %= p; return a < 0 ? a + p : a; }

// Smooth value noise, lattice cell `cell` texels, tileable over pw x ph texels
static float vnoise(float u, float v, float cell, int pw, int ph, uint32_t seed) {
  int cw = imax(1, (int)(pw / cell + 0.5f)), ch = imax(1, (int)(ph / cell + 0.5f));
  float x = u / cell, y = v / cell;
  int x0 = (int)floorf(x), y0 = (int)floorf(y);
  float fx = x - x0, fy = y - y0;
  fx = fx * fx * (3 - 2 * fx);
  fy = fy * fy * (3 - 2 * fy);
  int xa = wrapI(x0, cw), xb = wrapI(x0 + 1, cw), ya = wrapI(y0, ch), yb = wrapI(y0 + 1, ch);
  float a = hrand(xa, ya, seed), b = hrand(xb, ya, seed);
  float c = hrand(xa, yb, seed), d = hrand(xb, yb, seed);
  return (a + (b - a) * fx) + ((c + (d - c) * fx) - (a + (b - a) * fx)) * fy;
}

// Fractal noise in [0,1): octaves from `cell` down, skipping octaves finer
// than the texel footprint px (coarse mip levels get smoother noise).
static float fbm(float u, float v, float cell, int oct, int pw, int ph, float px, uint32_t seed) {
  float sum = 0, amp = 1, norm = 0;
  for (int o = 0; o < oct; o++) {
    if (cell < px * 1.5f && o > 0) break;
    sum += vnoise(u, v, cell, pw, ph, seed + (uint32_t)o * 7919u) * amp;
    norm += amp;
    amp *= 0.5f;
    cell *= 0.5f;
    if (cell < 1.0f) break;
  }
  return norm > 0 ? sum / norm : 0.5f;
}

// Per-texel speckle (only on level 0: it would alias on coarse levels)
static inline float speck(float u, float v, float px, uint32_t seed) {
  if (px > 1.0f) return 0.5f;
  return hrand((int)u, (int)v, seed);
}

static inline bool inR(float x, float y, float x0, float y0, float x1, float y1) {
  return x >= x0 && x < x1 && y >= y0 && y < y1;
}

// Noise-driven material shade: dark / shade / base / light
static inline uint8_t matShade(float n, float lo, float hi) {
  return n < lo ? TS_SHADE : (n > hi ? TS_LIGHT : TS_BASE);
}

// ═══════════════════════════════════════════════════════════════
//  WALL TEXTURE DESIGNS  (u, v: level-0 texel coordinates, v = 0 at
//  the top of the texture; mx/my: coordinates inside a module)
// ═══════════════════════════════════════════════════════════════
static uint8_t officeEval(bool ribbon, float u, float v, float px, int W) {
  const float mx = fmodf(u, 16.0f);
  float n = fbm(u, v, 8, 3, W, 48, px, 0x0FF1u) * 0.7f + speck(u, v, px, 0x0FF2u) * 0.3f;
  if (v < 16) {                                  // CAP: coping, shadow line, parapet, slab
    const float my = v;
    if (my < 2) return TS_TRIM;
    if (my < 3) return TS_DARK;
    if (my < 8) return matShade(n, 0.32f, 0.70f);
    if (my < 9) return TS_LIGHT;
    return TS_ALT;
  }
  if (v >= 32) {                                 // BASE: lobby glazing, granite piers
    const float my = v - 32;
    if (my < 2) return TS_ALT2;
    if (my < 3) return TS_TRIM;
    if (my >= 15) return TS_DARK;
    if (mx < 1 || mx >= 15) return TS_ALT2;
    if (mx < 2 && px <= 1) return TS_FRAME;
    if ((mx >= 5 && mx < 6) || (mx >= 10 && mx < 11)) return TS_FRAME;
    if (my < 4) return TS_FRAME;
    if (my < 7) return TS_WINB;
    if (my < 8 && px <= 1) return TS_FRAME;
    return TS_EMITA;                             // lobby (lit at night)
  }
  const float my = v - 16;                       // BODY: one floor
  if (ribbon) {
    if (my >= 4 && my < 13) {
      if (my < 5) return TS_DARK;                // shadow under the spandrel
      if (fmodf(mx, 4.0f) < 1.0f && px <= 2) return TS_FRAME;
      if (my < 7) return TS_WINB;
      if (my >= 12) return TS_WINC;
      return TS_WINA;
    }
    if (my >= 13 && my < 14) return TS_LIGHT;   // sill line
    if (mx < 1 && px <= 1) return TS_SHADE;     // spandrel panel joint
    return n < 0.3f ? TS_ALT2 : TS_ALT;
  }
  if (my < 3) return my < 1 ? TS_LIGHT : TS_ALT; // slab band
  if (mx < 2 || mx >= 14) return matShade(n, 0.30f, 0.72f);   // piers
  if (my >= 13) {                                 // sill + wall under it
    if (my < 14) return TS_TRIM;
    if (my < 15) return TS_TRIMD;
    return TS_ALT;
  }
  if (my < 4) return TS_DARK;                     // head soffit shadow (recess)
  if (mx < 3) return TS_SHADE;                    // side reveal in shadow
  if (mx >= 13 || my < 5) return TS_FRAME;
  if (mx >= 8 && mx < 9 && px <= 1) return TS_FRAME;   // mullion
  if (my < 8) return TS_WINB;
  if (my >= 12) return TS_WINC;
  return TS_WINA;
}

static uint8_t glassEval(float u, float v, float px, int W) {
  const float mx = fmodf(u, 8.0f);
  if (v < 16) {                                   // CAP: metal crown + opaque top floor
    const float my = v;
    if (my < 2) return TS_TRIM;
    if (my < 4) return TS_FRAME;
    if (mx < 1 && px <= 2) return TS_FRAME;
    if (my >= 15) return TS_FRAME;
    return (fmodf(my, 4.0f) < 1.0f && px <= 1) ? TS_SHADE : TS_ALT;
  }
  if (v >= 32) {                                  // BASE: lobby with a canopy
    const float my = v - 32;
    if (my < 1) return TS_TRIM;
    if (my < 3) return TS_DARK;
    if (my >= 15) return TS_DARK;
    if (mx < 1) return TS_FRAME;
    if (my < 5) return TS_WINB;
    return TS_EMITA;
  }
  const float my = v - 16;                        // BODY: curtain wall
  if (mx < 1 && px <= 2) return TS_FRAME;         // mullion
  if (my < 1 && px <= 1) return TS_FRAME;         // floor line
  if (my >= 14) return TS_ALT;                    // spandrel panel
  // reflection bands: vertical (continuous from floor to floor)
  float r = fbm(u, 0, 6, 2, W, 8, px, 0x6A55u);
  float diag = fmodf(u * 0.5f + my * 0.35f, 8.0f) < 1.2f ? 0.18f : 0.0f;   // glint streaks
  r += diag;
  if (r < 0.36f) return TS_WINC;
  if (r < 0.66f) return TS_WINA;
  return TS_WINB;
}

static uint8_t brickBond(float u, float v, float px) {
  // courses of 2 texels: brick row + mortar row; head joints every 4,
  // offset by 2 on alternate courses (running bond)
  int course = (int)(v / 2.0f);
  float cy = v - course * 2.0f;
  if (px <= 1 && cy >= 1.0f) return TS_ALT;                 // bed joint
  float bx = u + ((course & 1) ? 2.0f : 0.0f);
  if (px <= 1 && fmodf(bx, 4.0f) < 1.0f) return TS_ALT;     // head joint
  if (px > 1) {
    float n = fbm(u, v, 4, 2, 16, 48, px, 0xB21Cu);
    return n < 0.40f ? TS_SHADE : (n > 0.70f ? TS_LIGHT : TS_BASE);
  }
  uint32_t h = hash32((uint32_t)((int)(bx / 4.0f)) * 0x9E37u + (uint32_t)course * 0x85EBu + 0xB1u);
  int k = h & 7;
  return k < 2 ? TS_SHADE : (k < 6 ? TS_BASE : TS_LIGHT);
}

static uint8_t brickEval(float u, float v, float px) {
  const float mx = fmodf(u, 16.0f);
  if (v < 16) {                                   // CAP: cornice with dentils
    const float my = v;
    if (my < 2) return TS_TRIM;
    if (my < 3) return TS_DARK;
    if (my < 4) return fmodf(mx, 2.0f) < 1.0f ? TS_TRIM : TS_TRIMD;
    if (my >= 8 && my < 9) return TS_ALT2;        // soldier course
    return brickBond(u, v, px);
  }
  const bool base = v >= 32;
  const float my = v - (base ? 32 : 16);
  if (base && my >= 13) return my < 14 ? TS_TRIM : TS_ALT2;   // plinth
  // two windows per module: x in [x0, x0 + 6)
  const float x0 = mx < 8 ? 1.0f : 9.0f, wx = mx - x0;
  const float top = base ? 2.0f : 3.0f, bot = base ? 12.0f : 12.0f;
  if (my >= top - 1 && my < top && wx >= -1 && wx < 7) return TS_TRIM;     // lintel
  if (my >= bot && my < bot + 1 && wx >= -1 && wx < 7) return TS_TRIM;     // sill
  if (my >= bot + 1 && my < bot + 2 && wx >= 0 && wx < 6) return TS_TRIMD; // sill shadow
  if (my >= top && my < bot && wx >= 0 && wx < 6) {
    if (my < top + 1) return TS_DARK;                 // head reveal shadow
    if (wx < 1 || wx >= 5) return TS_FRAME;
    if (wx >= 3 && wx < 3.0f + 0.0f) return TS_FRAME;
    if (my < top + 3) return TS_WINB;
    if (my >= bot - 1) return TS_WINC;
    return TS_WINA;
  }
  return brickBond(u, v, px);
}

static uint8_t ashlar(float u, float v, float px, bool rustic) {
  int course = (int)(v / 4.0f);
  float cy = v - course * 4.0f;
  if (px <= 1 && cy < 1.0f) return rustic ? TS_DARK : TS_SHADE;
  float bx = u + ((course & 1) ? 4.0f : 0.0f);
  if (px <= 2 && fmodf(bx, 8.0f) < 1.0f) return rustic ? TS_DARK : TS_SHADE;
  uint32_t h = hash32((uint32_t)((int)(bx / 8.0f)) * 0x51u + (uint32_t)course * 0x9Fu + 0x57u);
  float n = speck(u, v, px, 0x5701u);
  if (n < 0.08f) return TS_SHADE;
  return (h & 3) == 0 ? TS_LIGHT : TS_BASE;
}

static uint8_t stoneEval(float u, float v, float px) {
  const float mx = fmodf(u, 16.0f);
  if (v < 16) {                                   // CAP: grand cornice
    const float my = v;
    if (my < 1) return TS_TRIM;
    if (my < 2) return TS_LIGHT;
    if (my < 3) return TS_TRIM;
    if (my < 4) return TS_DARK;
    if (my < 5) return fmodf(mx, 2.0f) < 1.0f ? TS_TRIM : TS_DARK;   // dentils
    if (my < 6) return TS_TRIMD;
    if (my < 9) return TS_ALT;                    // frieze
    if (my < 10) return TS_TRIM;                  // architrave
    return ashlar(u, v, px, false);
  }
  if (v >= 32) {                                  // BASE: rusticated, arched opening
    const float my = v - 32;
    float dx = mx - 8.0f, dy = my - 8.5f;
    bool inArch = (my >= 8.5f && mx >= 3 && mx < 13) || (my < 8.5f && dx * dx + dy * dy < 25.0f);
    bool inGlass = (my >= 8.5f && mx >= 4 && mx < 12) || (my < 8.5f && dx * dx + dy * dy < 16.0f);
    if (my >= 15) return TS_DARK;
    if (inGlass) {
      if (mx >= 7.5f && mx < 8.5f && px <= 1) return TS_FRAME;
      return my < 7 ? TS_WINB : TS_EMITA;
    }
    if (inArch) return my < 4 && mx >= 7 && mx < 9 ? TS_TRIM : TS_TRIMD;   // keystone / voussoirs
    return ashlar(u, v, px, true);
  }
  const float my = v - 16;                        // BODY: tall window with a hood
  if (my >= 14) return my < 15 ? TS_TRIM : TS_TRIMD;       // string course
  if (my >= 1 && my < 2 && mx >= 4 && mx < 12) return TS_TRIM;      // hood
  if (my >= 2 && my < 3 && mx >= 4 && mx < 12) return TS_TRIMD;
  if (my >= 12 && my < 13 && mx >= 4 && mx < 12) return TS_TRIM;    // sill
  if (my >= 13 && my < 14 && mx >= 5 && mx < 11) return TS_TRIMD;
  if (my >= 3 && my < 12 && mx >= 5 && mx < 11) {
    if (mx < 6 || mx >= 10 || my < 4) return TS_FRAME;
    if (px <= 1 && ((mx >= 8 && mx < 9) || (my >= 7 && my < 8))) return TS_FRAME;
    if (my < 7) return TS_WINB;
    if (my >= 11) return TS_WINC;
    return TS_WINA;
  }
  return ashlar(u, v, px, false);
}

static uint8_t modernEval(float u, float v, float px) {
  const float mx = fmodf(u, 16.0f);
  const bool strip = mx >= 7 && mx < 9;
  if (v < 16) {                                   // CAP: crown lights
    const float my = v;
    if (my < 2) return TS_EMITB;
    if (my < 5) return TS_ALT2;
    if (my < 6) return TS_EMITB;
    if (strip) return TS_EMITA;
    return (px <= 1 && my >= 15) ? TS_SHADE : TS_BASE;
  }
  if (v >= 32) {                                  // BASE: double-height lobby
    const float my = v - 32;
    if (my < 2) return TS_TRIM;
    if (my >= 15) return TS_DARK;
    if (mx < 1 || mx >= 15) return TS_ALT2;
    if ((mx >= 5 && mx < 6) || (mx >= 10 && mx < 11)) return TS_FRAME;
    return my < 4 ? TS_WINB : TS_EMITA;
  }
  const float my = v - 16;                        // BODY
  if (strip) return TS_EMITA;                     // vertical light strip
  if (px <= 1 && (my >= 15 || mx < 1)) return TS_SHADE;      // panel joints
  if (my >= 3 && my < 13 && ((mx >= 2 && mx < 6) || (mx >= 10 && mx < 14))) {
    if (my < 6) return TS_WINB;
    if (my >= 12) return TS_WINC;
    return TS_WINA;
  }
  float n = speck(u, v, px, 0x30D3u);
  return n < 0.1f ? TS_LIGHT : TS_BASE;
}

static uint8_t shopsEval(float u, float v, float px, int W) {
  const float mx = fmodf(u, 32.0f);
  float n = fbm(u, v, 8, 2, W, 48, px, 0x5409u) * 0.6f + speck(u, v, px, 0x540Au) * 0.4f;
  if (v < 16) {                                   // CAP
    const float my = v;
    if (my < 2) return TS_TRIM;
    if (my < 3) return TS_DARK;
    if (my < 6) return TS_ALT;
    return matShade(n, 0.25f, 0.78f);
  }
  if (v >= 32) {                                  // BASE: two shopfronts
    const float my = v - 32;
    const bool shopA = mx < 16;
    const float sx = shopA ? mx : mx - 16;
    if (my < 2) return TS_TRIM;                   // fascia
    if (my < 6) {                                 // sign board with letters
      if (sx < 1 || sx >= 15) return TS_TRIMD;
      if (my >= 3 && my < 5 && sx >= 2 && sx < 14) {
        uint32_t h = hash32((uint32_t)sx * 31u + (shopA ? 7u : 91u));
        bool gap = fmodf(sx - 2, 3.0f) >= 2.0f;
        if (!gap && (h & 3) != 0) return TS_EMITB;
      }
      return shopA ? TS_ACC2 : TS_FRAME;
    }
    if (my < 8) return fmodf(sx, 4.0f) < 2.0f ? TS_ACC : TS_TRIM;     // striped awning
    if (my < 9) return fmodf(sx, 2.0f) < 1.0f ? TS_ACC : TS_DARK;     // scalloped edge
    if (my >= 15) return TS_ALT2;                 // stall riser
    if (sx < 1 || sx >= 15) return TS_FRAME;
    float dx0 = shopA ? 10.0f : 2.0f;             // door
    if (sx >= dx0 && sx < dx0 + 3) return (sx < dx0 + 1 || my < 10) ? TS_FRAME : TS_WINC;
    if (sx >= 6 && sx < 7 && px <= 1) return TS_FRAME;
    return TS_EMITA;                              // shop window (lit at night)
  }
  const float my = v - 16;                        // BODY: flats with shutters / balconies
  const int wi = (int)(mx / 8.0f);
  const float x0 = wi * 8.0f + 2.0f, wx = mx - x0;
  const bool shutters = (wi & 1) == 0;
  if (my >= 4 && my < 12) {
    if (wx >= 0 && wx < 4) {
      if (my < 6) return TS_WINB;
      return TS_WINA;
    }
    if (shutters && ((wx >= -2 && wx < 0) || (wx >= 4 && wx < 6)))
      return fmodf(my, 2.0f) < 1.0f ? TS_ACC : TS_ACC2;
    if (wx >= -1 && wx < 5) return TS_TRIM;       // surround
  }
  if (my >= 12 && my < 13 && wx >= -1 && wx < 5) return TS_TRIM;     // sill
  if (!shutters && my >= 10 && my < 13 && wx >= -2 && wx < 6) {      // balcony rail
    if (my < 11 || fmodf(mx, 2.0f) < 1.0f) return TS_FRAME;
  }
  if (my >= 3 && my < 4 && wx >= -1 && wx < 5) return TS_TRIM;
  return matShade(n, 0.25f, 0.78f);
}

static uint8_t villaEval(float u, float v, float px, int W) {
  const float mx = fmodf(u, 16.0f);
  float n = speck(u, v, px, 0x711Au);
  uint8_t stucco = n < 0.06f ? TS_SHADE : (n > 0.94f ? TS_LIGHT : TS_BASE);
  if (v < 16) {                                   // CAP: eave shadow + frieze
    const float my = v;
    if (my < 2) return TS_DARK;
    if (my < 3) return TS_TRIMD;
    if (my < 4) return TS_TRIM;
    return stucco;
  }
  const bool base = v >= 32;
  const float my = v - (base ? 32 : 16);
  if (base && my >= 13) return my < 14 ? TS_TRIMD : TS_ALT;          // stone plinth
  const float wt = base ? 3.0f : 4.0f, wb = base ? 13.0f : 11.0f;
  if (my >= wt && my < wb) {
    if (mx >= 6 && mx < 10) return my < wt + 2 ? TS_WINB : TS_WINA;  // window / French door
    if ((mx >= 3 && mx < 5) || (mx >= 11 && mx < 13))                // shutters
      return fmodf(my, 2.0f) < 1.0f ? TS_ACC : TS_ACC2;
    if (mx >= 5 && mx < 11) return TS_TRIM;
  }
  if ((my >= wt - 1 && my < wt) && mx >= 5 && mx < 11) return TS_TRIM;
  if ((my >= wb && my < wb + 1) && mx >= 5 && mx < 11) return TS_TRIM;
  if (base && my >= 11 && my < 13 && ((mx >= 1 && mx < 3) || (mx >= 13 && mx < 15)))
    return my < 12 ? TS_ACC2 : TS_TRIMD;           // potted plants
  (void)W;
  return stucco;
}

static uint8_t cliffEval(float u, float v, float px, int W) {
  // Layered rock: strata 8 texels thick (4 per 32-row body period, so the
  // body tiles), wavy along the wall; each stratum is split into blocks
  // by fissures; lit ledge tops, shadowed undersides, a few tufts.
  const float vb = v - 16.0f;                        // body coordinates (cap above: < 0)
  const float wob = (fbm(u, 0, 16, 2, W, 8, px, 0xC1F0u) - 0.5f) * 3.0f;
  const float s = (vb + wob + 64.0f) / 8.0f;
  const int layer = (int)floorf(s);
  const float f = (s - (float)layer) * 8.0f;          // texels into the stratum (0 = top)
  if (v < 16) {                                       // CAP: scrub on the top edge
    float edge = 2.5f + fbm(u, 0, 4, 2, W, 8, px, 0xC1F2u) * 3.5f;
    if (v < edge) return fbm(u, v, 4, 2, W, 48, px, 0xC1F4u) < 0.5f ? TS_ACC2 : TS_ACC;
    if (v < edge + 1.0f) return TS_DARK;
  }
  const uint32_t lh = hash32((uint32_t)wrapI(layer, 4) * 0x68E3u + 0xC1u);
  const float bw = (lh & 16) ? 16.0f : 8.0f;           // block width (divides 32: tiles)
  const float bx = u + (float)(lh & 31);
  const int block = (int)floorf(bx / bw);
  const float fx = bx - (float)block * bw;
  const uint32_t bh = hash32((uint32_t)wrapI(block, (int)(32.0f / bw)) * 0x9E37u + lh);
  if (px <= 2 && fx < 1.0f) return TS_DARK;           // fissure between blocks
  if (f < 1.3f) return (f < 1.0f && (bh & 15) == 0 && px <= 2) ? TS_ACC2 : TS_LIGHT;   // ledge
  if (f >= 7.0f && px <= 2) return TS_DARK;           // shadow under the next ledge
  if (px <= 1 && fx > bw - 1.0f) return TS_SHADE;     // block edge away from the light
  const float n = fbm(u, v, 8, 2, W, 48, px, 0xC1F1u);
  const float k = n * 0.55f + (float)(bh % 3) * 0.18f + (f < 3.0f ? 0.12f : 0.0f);
  if (k < 0.30f) return TS_SHADE;
  if (k < 0.48f) return TS_ALT;
  if (k < 0.78f) return TS_BASE;
  return TS_LIGHT;
}

static uint8_t wallEval(float u, float v, float px) {
  const float mx = fmodf(u, 16.0f);
  float n = speck(u, v, px, 0x3A11u);
  float m = fbm(u, v, 8, 2, 16, 48, px, 0x3A12u);
  if (v < 16 && v < 3) return TS_TRIM;            // coping
  if (v >= 3 && v < 4) return TS_DARK;            // drip shadow
  const bool base = v >= 32;
  const float my = fmodf(v, 16.0f);
  if (px <= 1 && mx < 1) return TS_DARK;          // vertical panel joint
  if (px <= 1 && my >= 15) return TS_DARK;        // horizontal joint
  if (base && my >= 12) {
    if (n < 0.08f) return TS_ACC2;                // moss
    return TS_ALT;                                // dirty footing
  }
  if (base && my >= 9 && my < 10 && mx >= 7 && mx < 9) return TS_DARK;   // weep hole
  if (px <= 1 && ((mx >= 3 && mx < 4) || (mx >= 11 && mx < 12)) &&
      ((my >= 3 && my < 4) || (my >= 11 && my < 12)))
    return TS_SHADE;                              // form-tie holes
  // water stains running down from the joints
  uint32_t sh = hash32((uint32_t)((int)mx) * 0x45u + 0x3Au);
  if ((sh & 7) == 0 && my < 4.0f + (float)((sh >> 4) & 7)) return TS_ALT2;
  if (m < 0.32f) return TS_SHADE;
  if (n > 0.93f || m > 0.75f) return TS_LIGHT;
  return TS_BASE;
}

static uint8_t tunnelEval(float u, float v, float px) {
  const float mx = fmodf(u, 16.0f);
  if (v < 16) {                                   // CAP: dark haunch, cable tray
    if (v >= 3 && v < 6) {
      if (v < 4 || fmodf(mx, 8.0f) < 1.0f) return TS_FRAME;
      return TS_TRIMD;
    }
    if (v >= 15) return TS_DARK;
    return TS_ALT2;
  }
  if (v >= 48) {                                  // BASE: skirting, marker lights, kerb
    const float my = v - 48;
    if (my < 2) return TS_TRIM;
    if (my >= 14) return TS_TRIMD;
    if (my >= 6 && my < 8 && mx >= 7 && mx < 9) return TS_EMITB;
    return speck(u, v, px, 0x7E1u) < 0.12f ? TS_DARK : TS_ALT;
  }
  const float my = v - 16;                        // BODY: stripe + tiles
  if (my < 4) return TS_ACC;
  if (my >= 22 && my < 24) return TS_ACC2;
  float ty = my - 4;
  if (px <= 1 && (fmodf(mx, 8.0f) < 1.0f || fmodf(ty, 6.0f) < 1.0f)) return TS_SHADE;   // grout
  uint32_t h = hash32((uint32_t)((int)(mx / 8.0f)) * 0x7Fu + (uint32_t)((int)(ty / 6.0f)) * 0x3Du + 0x71u);
  return (h % 5) == 0 ? TS_LIGHT : TS_BASE;
}

static uint8_t roofEval(float u, float v, float px) {
  // barrel tiles: ridge highlight / channel shadow every 4, courses every 4
  const float cx = fmodf(u, 4.0f), cy = fmodf(v, 4.0f);
  if (px <= 1 && cy >= 3) return TS_DARK;
  uint32_t h = hash32((uint32_t)((int)(u / 4.0f)) * 0x3Bu + (uint32_t)((int)(v / 4.0f)) * 0x95u + 0x12u);
  if (px > 1) return (h & 3) == 0 ? TS_ALT : TS_BASE;
  if (cx < 1) return TS_SHADE;
  if (cx >= 2 && cx < 3) return TS_LIGHT;
  return (h & 3) == 0 ? TS_ALT : TS_BASE;
}

static uint8_t evalWall(int id, float u, float v, float px, int W) {
  switch (id) {
    case WT_OFFICE: return officeEval(false, u, v, px, W);
    case WT_RIBBON: return officeEval(true, u, v, px, W);
    case WT_GLASS:  return glassEval(u, v, px, W);
    case WT_BRICK:  return brickEval(u, v, px);
    case WT_STONE:  return stoneEval(u, v, px);
    case WT_MODERN: return modernEval(u, v, px);
    case WT_SHOPS:  return shopsEval(u, v, px, W);
    case WT_VILLA:  return villaEval(u, v, px, W);
    case WT_CLIFF:  return cliffEval(u, v, px, W);
    case WT_WALL:   return wallEval(u, v, px);
    case WT_TUNNEL: return tunnelEval(u, v, px);
    case WT_ROOF:   return roofEval(u, v, px);
    default:        return TS_BASE;
  }
}

// ═══════════════════════════════════════════════════════════════
//  GROUND TEXTURE DESIGNS (u across the road, v along it)
// ═══════════════════════════════════════════════════════════════
static float crackX(float v) {   // a wandering crack along the tile
  return 52.0f + 3.0f * sinf(v * 0.31f) + 1.5f * sinf(v * 1.13f + 1.0f);
}

static uint8_t asphaltEval(float u, float v, float px) {
  const int W = 64, H = 32;
  float n = fbm(u, v, 8, 3, W, H, px, 0xA5F1u) * 0.55f + speck(u, v, px, 0xA5F2u) * 0.45f;
  // repair patch
  if (inR(u, v, 8, 6, 30, 22)) {
    if (px <= 1 && (u < 9 || u >= 29 || v < 7 || v >= 21)) return TS_ALT2;
    return n > 0.80f ? TS_LIGHT : TS_ALT;
  }
  // tar-sealed seam along the road
  if (fabsf(u - (40.0f + 2.5f * sinf(v * 0.2f))) < (px <= 1 ? 0.9f : 1.2f)) return TS_ACC;
  // crack
  if (px <= 2 && fabsf(u - crackX(v)) < 0.6f) return TS_FRAME;
  if (px <= 1 && v > 12 && v < 20 && fabsf(u - (crackX(v) + (v - 12) * 0.9f)) < 0.5f) return TS_FRAME;
  // oil drip blotch
  {
    float dx = (u - 20.0f) / 5.0f, dy = (v - 27.0f) / 3.5f;
    if (dx * dx + dy * dy + (fbm(u, v, 2, 1, W, H, px, 0xA5F3u) - 0.5f) < 0.9f) return TS_ACC2;
  }
  if (n < 0.04f) return TS_DARK;
  if (n < 0.27f) return TS_SHADE;
  if (n > 0.95f) return TS_TRIM;
  if (n > 0.72f) return TS_LIGHT;
  return TS_BASE;
}

static uint8_t pavementEval(float u, float v, float px) {
  // u: 0 at the road edge, 32 at the building line (|x| 1.0 .. 1.5)
  if (u < 0.8f) return TS_DARK;                   // gutter / kerb face
  if (u < 4.5f) {                                 // granite kerb, a joint per segment
    if (px <= 1 && fmodf(v, 8.0f) < 0.7f) return TS_SHADE;
    return speck(u, v, px, 0x9A1u) < 0.25f ? TS_TRIMD : TS_TRIM;
  }
  if (u < 5.2f) return TS_SHADE;                  // kerb back joint
  const float su = u - 5.2f, sw = (32.0f - 5.2f) / 4.0f;
  if (px <= 1 && (fmodf(su, sw) < 0.7f || fmodf(v, 8.0f) < 0.7f)) return TS_SHADE;
  uint32_t h = hash32((uint32_t)((int)(su / sw)) * 0x6Du + (uint32_t)((int)(v / 8.0f)) * 0xB5u + 0x9Au);
  float n = speck(u, v, px, 0x9A2u);
  if (n < 0.05f) return TS_ALT2;                  // stain / gum
  if (n > 0.95f) return TS_LIGHT;
  int k = (int)(h % 6);
  return k == 0 ? TS_ALT : (k == 1 ? TS_LIGHT : TS_BASE);
}

static uint8_t grassEval(float u, float v, float px) {
  float n = fbm(u, v, 8, 3, 16, 16, px, 0x6A5u) * 0.6f + speck(u, v, px, 0x6A6u) * 0.4f;
  float f = speck(u, v, px, 0x6A7u);
  if (f > 0.985f) return TS_ACC;                  // yellow flower
  if (f < 0.012f) return TS_ACC2;                 // white flower
  if (n < 0.22f) return TS_DARK;
  if (n < 0.42f) return TS_SHADE;
  if (n > 0.74f) return TS_LIGHT;
  return TS_BASE;
}

static uint8_t sandEval(float u, float v, float px) {
  float n = fbm(u, v, 8, 2, 16, 16, px, 0x5A1u) * 0.5f + speck(u, v, px, 0x5A2u) * 0.5f;
  float r = fmodf(v + 1.6f * sinf(u * 0.3926991f * 2.0f) + 16.0f, 4.0f);   // wind ripples
  if (px <= 1 && r < 0.8f) return TS_SHADE;
  if (speck(u, v, px, 0x5A3u) > 0.985f) return TS_TRIM;   // shell
  if (n < 0.30f) return TS_SHADE;
  if (n > 0.72f) return TS_LIGHT;
  return TS_BASE;
}

static uint8_t waterEval(float u, float v, float px) {
  // crests roughly along the shore (constant u), wobbling, plus glints
  float w = u + 2.0f * sinf(v * 0.3926991f) + 3.0f * (fbm(u, v, 8, 2, 32, 32, px, 0xA71u) - 0.5f);
  float c = fmodf(w + 64.0f, 8.0f);
  float s = speck(u, v, px, 0xA72u);
  if (s > 0.975f) return TS_TRIM;                 // glint
  if (c < 1.0f) return TS_LIGHT;                  // crest
  if (c < 2.0f) return TS_BASE;
  if (c > 6.0f) return TS_SHADE;                  // trough
  return s < 0.15f ? TS_SHADE : TS_BASE;
}

static uint8_t rockEval(float u, float v, float px) {
  float n = fbm(u, v, 4, 3, 16, 16, px, 0x40C1u) * 0.6f + speck(u, v, px, 0x40C2u) * 0.4f;
  if (n < 0.18f) return TS_DARK;
  if (n < 0.38f) return TS_SHADE;
  if (n > 0.80f) return TS_LIGHT;
  return TS_BASE;
}

static uint8_t snowEval(float u, float v, float px) {
  float n = fbm(u, v, 8, 2, 16, 16, px, 0x5E1u);
  float s = speck(u, v, px, 0x5E2u);
  if (s > 0.97f) return TS_TRIM;                  // sparkle
  if (n < 0.30f) return TS_SHADE;
  if (n > 0.70f) return TS_LIGHT;
  return TS_BASE;
}

static uint8_t dirtEval(float u, float v, float px) {
  float n = fbm(u, v, 6, 3, 16, 16, px, 0xD1u) * 0.6f + speck(u, v, px, 0xD2u) * 0.4f;
  float s = speck(u, v, px, 0xD3u);
  if (s > 0.96f) return TS_LIGHT;                 // pebble
  if (s < 0.04f) return TS_DARK;
  if (n < 0.35f) return TS_SHADE;
  if (n > 0.70f) return TS_LIGHT;
  return TS_BASE;
}

static uint8_t evalRow(int id, float u, float v, float px) {
  switch (id) {
    case RT_ASPHALT:  return asphaltEval(u, v, px);
    case RT_PAVEMENT: return pavementEval(u, v, px);
    case RT_GRASS:    return grassEval(u, v, px);
    case RT_SAND:     return sandEval(u, v, px);
    case RT_WATER:    return waterEval(u, v, px);
    case RT_ROCK:     return rockEval(u, v, px);
    case RT_SNOW:     return snowEval(u, v, px);
    case RT_DIRT:     return dirtEval(u, v, px);
    default:          return TS_BASE;
  }
}

// ═══════════════════════════════════════════════════════════════
//  GENERATION
// ═══════════════════════════════════════════════════════════════
static inline bool isWindowSlot(uint8_t s) {
  return s == TS_WINA || s == TS_WINB || s == TS_WINC || s == TS_EMITA || s == TS_EMITB;
}

static size_t wallBytes(const WallDef& d) {
  size_t rows = (size_t)d.cap + d.body + d.base, total = 0;
  for (int l = 0; l < TEX_LEVELS; l++) total += (((size_t)1 << d.wLog2) >> l) * (rows >> l) + (rows >> l);
  return total;
}

static size_t rowBytes(const RowDef& d) {
  size_t total = 0;
  for (int l = 0; l < TEX_LEVELS; l++) total += (((size_t)1 << d.wLog2) >> l) * (((size_t)1 << d.hLog2) >> l);
  return total;
}

static uint8_t* genWall(int id, uint8_t* p) {
  const WallDef& d = WALL_DEFS[id];
  WallTex& T = sWall[id];
  T.wLog2 = d.wLog2; T.cap = d.cap; T.body = d.body; T.base = d.base;
  T.rows = (uint8_t)(d.cap + d.body + d.base);
  T.winShift = d.winShift;
  const int W0 = 1 << d.wLog2, R0 = T.rows;
  for (int l = 0; l < TEX_LEVELS; l++) {
    const int W = W0 >> l, R = R0 >> l;
    const float px = (float)(1 << l);
    uint8_t* lev = p;
    for (int x = 0; x < W; x++)
      for (int y = 0; y < R; y++)
        lev[x * R + y] = evalWall(id, (x + 0.5f) * px, (y + 0.5f) * px, px, W0);
    p += W * R;
    // averaged column: per row, the majority slot; window-ish slots win
    // when they cover at least 35 % of the row (grazing views keep floors)
    uint8_t* avg = p;
    for (int y = 0; y < R; y++) {
      int cnt[TS_COUNT];
      memset(cnt, 0, sizeof(cnt));
      for (int x = 0; x < W; x++) cnt[lev[x * R + y]]++;
      int best = TS_BASE, bestN = -1, bestWin = -1, bestWinN = 0, winTotal = 0;
      for (int s = 0; s < TS_COUNT; s++) {
        if (isWindowSlot((uint8_t)s)) { winTotal += cnt[s]; if (cnt[s] > bestWinN) { bestWinN = cnt[s]; bestWin = s; } }
        else if (cnt[s] > bestN) { bestN = cnt[s]; best = s; }
      }
      avg[y] = (uint8_t)((bestWin >= 0 && winTotal * 100 >= W * 35) ? bestWin : best);
    }
    p += R;
    T.lev[l] = lev;
    T.avg[l] = avg;
  }
  return p;
}

static uint8_t* genRow(int id, uint8_t* p) {
  const RowDef& d = ROW_DEFS[id];
  RowTex& T = sRow[id];
  T.wLog2 = d.wLog2; T.hLog2 = d.hLog2;
  for (int l = 0; l < TEX_LEVELS; l++) {
    const int W = (1 << d.wLog2) >> l, H = (1 << d.hLog2) >> l;
    const float px = (float)(1 << l);
    for (int y = 0; y < H; y++)
      for (int x = 0; x < W; x++)
        p[y * W + x] = evalRow(id, (x + 0.5f) * px, (y + 0.5f) * px, px);
    T.lev[l] = p;
    p += W * H;
  }
  return p;
}

// START / FINISH banner: chequered ends, a light frame, letters from the
// 5x7 font at 2x
static void genBanner(uint8_t* b, const char* text) {
  const int W = TEX_BANNER_W, H = TEX_BANNER_H;
  for (int y = 0; y < H; y++)
    for (int x = 0; x < W; x++) {
      uint8_t s = TS_DARK;
      if (y == 0 || y == H - 1) s = TS_TRIM;
      else if (x < 18 || x >= W - 18) {
        int cx = (x < 18 ? x : x - (W - 18)) / 3, cy = (y - 1) / 3;
        s = ((cx + cy) & 1) ? TS_LIGHT : TS_SHADE;
      } else if (x < 20 || x >= W - 20) s = TS_TRIM;
      b[y * W + x] = s;
    }
  int n = (int)strlen(text);
  int tw = n * 12 - 2;
  int x0 = (W - tw) / 2, y0 = 1;
  for (int i = 0; i < n; i++) {
    const uint8_t* g = gfx_fontGlyph(text[i]);
    for (int r = 0; r < 7; r++)
      for (int c = 0; c < 5; c++)
        if (g[r] & (0x10 >> c))
          for (int dy = 0; dy < 2; dy++)
            for (int dx = 0; dx < 2; dx++) {
              int x = x0 + i * 12 + c * 2 + dx, y = y0 + r * 2 + dy;
              if (x >= 0 && x < W && y >= 0 && y < H) b[y * W + x] = TS_EMITB;
            }
  }
}

bool textures_init() {
  if (sTried) return sReady;
  sTried = true;
  size_t total = 0;
  for (int i = 0; i < WT_COUNT; i++) total += wallBytes(WALL_DEFS[i]);
  for (int i = 0; i < RT_COUNT; i++) total += rowBytes(ROW_DEFS[i]);
  // Read per pixel by the hottest loops: internal SRAM first
  uint8_t* block = (uint8_t*)plat_alloc_internal(total);
  bool internal = block != nullptr;
  if (!block) block = (uint8_t*)plat_alloc_psram(total);
  if (!block) {
    plat_log("tex: no memory for %u B of textures, flat shading only\n", (unsigned)total);
    memset(sDummy, TS_BASE, sizeof(sDummy));
    for (int i = 0; i < WT_COUNT; i++) {
      sWall[i].wLog2 = 0; sWall[i].cap = 0; sWall[i].body = 8; sWall[i].base = 0; sWall[i].rows = 8;
      sWall[i].winShift = 4;
      for (int l = 0; l < TEX_LEVELS; l++) { sWall[i].lev[l] = sDummy; sWall[i].avg[l] = sDummy; }
    }
    for (int i = 0; i < RT_COUNT; i++) {
      sRow[i].wLog2 = 3; sRow[i].hLog2 = 3;
      for (int l = 0; l < TEX_LEVELS; l++) sRow[i].lev[l] = sDummy;
    }
    return false;
  }
  uint8_t* p = block;
  for (int i = 0; i < WT_COUNT; i++) p = genWall(i, p);
  for (int i = 0; i < RT_COUNT; i++) p = genRow(i, p);
  // Banners are drawn a few seconds per lap: PSRAM is fine
  const size_t bb = (size_t)TEX_BANNER_W * TEX_BANNER_H;
  uint8_t* banners = (uint8_t*)plat_alloc_psram(2 * bb);
  bool bannerInternal = false;
  if (!banners) { banners = (uint8_t*)plat_alloc_internal(2 * bb); bannerInternal = banners != nullptr; }
  if (banners) {
    sBanner[0] = banners;
    sBanner[1] = banners + bb;
    genBanner(sBanner[0], "START");
    genBanner(sBanner[1], "FINISH");
  }
  plat_log("tex: %d wall + %d ground textures with %d mips (%u B) in %s, banners (%u B) in %s\n",
           (int)WT_COUNT, (int)RT_COUNT, TEX_LEVELS, (unsigned)total, internal ? "internal SRAM" : "PSRAM",
           (unsigned)(2 * bb), banners ? (bannerInternal ? "internal SRAM" : "PSRAM") : "nowhere");
  sReady = true;
  return true;
}

